// ─── 결과 계산: 언어별 점수 합산 → 내림차순 순위 (동점 시 LOVE_KEYS 순서) ───
export function computeLoveRanking(answers, qs) {
  const sc = { words: 0, time: 0, gifts: 0, acts: 0, touch: 0 };
  answers.forEach((ai, qi) => {
    const w = qs[qi].options[ai].w;
    LOVE_KEYS.forEach((k) => { sc[k] += w[k]; });
  });
  return [...LOVE_KEYS].sort((a, b) => (sc[b] - sc[a]) || (LOVE_KEYS.indexOf(a) - LOVE_KEYS.indexOf(b)));
}

